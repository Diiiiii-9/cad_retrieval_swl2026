"""
PyTorch Geometric Dataset for CAD Graphs
========================================
@Author: Di Liu
@Date: 2026-05-01
@Description: 
Custom Dataset class to load the pre-processed .pt files generated by data_converter.py.
Designed to handle dynamic loading (to save RAM) and attach model identifiers 
so that embeddings can be traced back to their original CAD files during retrieval.
"""

import os
import pathlib
import logging
import torch
from torch_geometric.data import Dataset, Data

class CADGraphDataset(Dataset):
    def __init__(self, root_dir, transform=None, pre_transform=None):
        """
        Args:
            root_dir (str or Path): Directory containing the processed .pt files 
                                    (e.g., '../data/processed_graphs/').
            transform (callable, optional): A function/transform that takes in an 
                                            `torch_geometric.data.Data` object and returns a 
                                            transformed version (e.g., feature normalization).
            pre_transform (callable, optional): A function/transform that takes in an 
                                                `torch_geometric.data.Data` object and returns a 
                                                transformed version before saving to disk.
        """
        self.root_dir = pathlib.Path(root_dir)
        
        # Robustness: Check if directory exists
        if not self.root_dir.exists() or not self.root_dir.is_dir():
            raise FileNotFoundError(f"Dataset directory not found: {self.root_dir}")

        # Collect all .pt files and sort them to ensure consistent ordering across OS platforms
        self.file_paths = sorted(list(self.root_dir.glob("*.pt")))
        
        if len(self.file_paths) == 0:
            logging.warning(f"No .pt files found in {self.root_dir}. Did you run data_converter.py?")

        # Initialize the PyG Dataset base class
        # Note: We pass None for 'root' because we are managing the file paths manually,
        # bypassing PyG's default (and sometimes restrictive) processed/raw folder structure.
        super().__init__(root=None, transform=transform, pre_transform=pre_transform)

    def len(self):
        """Returns the total number of graphs in the dataset."""
        return len(self.file_paths)

    def get(self, idx):
        """
        Loads and returns a single graph Data object by its index.
        
        Args:
            idx (int): The index of the graph to retrieve.
            
        Returns:
            torch_geometric.data.Data: The graph data object representing a CAD model.
        """
        filepath = self.file_paths[idx]
        
        try:
            # Load the PyG Data object from disk
            data = torch.load(filepath)
            
            # -------------------------------------------------------------
            # CRITICAL FOR RETRIEVAL: Attach the filename (without extension) 
            # to the data object. This ensures that when the GNN generates 
            # an embedding, we know EXACTLY which CAD model it belongs to.
            # -------------------------------------------------------------
            data.name = filepath.stem 
            
            # Robustness check: Ensure edge_index exists even if the graph has isolated nodes
            if not hasattr(data, 'edge_index') or data.edge_index is None:
                data.edge_index = torch.empty((2, 0), dtype=torch.long)
                
            return data
            
        except Exception as e:
            # Robust error handling: Log the corrupt file and raise a clear error
            logging.error(f"Error loading graph file {filepath.name}: {e}")
            raise RuntimeError(f"Corrupted dataset file detected: {filepath.name}") from e

    def get_feature_dimensions(self):
        """
        Utility method to dynamically check the input dimensions of node and edge features.
        Useful for initializing the GNN model architecture dynamically.
        
        Returns:
            tuple: (num_node_features, num_edge_features)
        """
        if self.len() == 0:
            return 0, 0
            
        sample_data = self.get(0)
        
        # Check node feature shape (N, num_node_features)
        num_node_features = sample_data.x.shape[1] if sample_data.x is not None else 0
        
        # Check edge feature shape (E, num_edge_features)
        num_edge_features = sample_data.edge_attr.shape[1] if sample_data.edge_attr is not None else 0
            
        return num_node_features, num_edge_features

